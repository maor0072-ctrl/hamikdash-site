// חוצה חלונות שקט: תפיסה של שעה בערב שבת פוקעת במוצאי שבת, לא בתוכה.
// שומרים takenAt ותקציב, ולא שעת פקיעה מוכנה, כי שעת פקיעה שחושבה מראש
// נשברת ברגע שחלון שקט נפתח באמצע.
export function expiryFor(takenAt, budgetMs) {
  let t = Number(takenAt) || 0;
  let left = Number(budgetMs) || 0;
  if (!t) return 0;

  for (let pass = 0; pass < 64; pass++) {
    const w = windowContaining(t);
    if (w) {
      t = w[1];
      continue;
    }
    const next = nextWindowAfter(t);
    if (!next || t + left <= next[0]) return t + left;
    left -= next[0] - t;
    t = next[1];
  }
  return t + left;
}

export function inQuietWindow(ts) {
  return windowContaining(Number(ts) || 0) !== null;
}

export function quietWindowAt(ts) {
  return windowContaining(Number(ts) || 0);
}

function windowContaining(ts) {
  for (const w of QUIET_WINDOWS) {
    if (w[0] > ts) break;
    if (ts >= w[0] && ts < w[1]) return w;
  }
  return null;
}

function nextWindowAfter(ts) {
  for (const w of QUIET_WINDOWS) {
    if (w[0] > ts) return w;
  }
  return null;
}
